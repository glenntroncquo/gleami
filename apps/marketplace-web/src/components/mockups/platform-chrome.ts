export type PlatformChrome = (typeof chrome)[Language];

export function platformChrome(locale: Locale): PlatformChrome {
  return chrome[localeConfig[locale].language];
}

export function translateTreatment(locale: Locale, treatment: string) {
  const language = localeConfig[locale].language;
  return treatments[language][treatment] ?? treatment;
}
